#!/usr/bin/env python3
"""Render a biorouter `--output-format json` result into the MedCP benchmark
markdown format (matching the archived responses/ files: question header, full
response, per-step reasoning with tools called, performance metrics incl. time,
and every tool call with its input).

Usage:
    format_response.py --qname Q1.1 --question "..." --elapsed 74 \
        --date "2026-07-22 13:05:00" --model gpt-5.5-2026-04-24 \
        --provider versa_azure --kg on --json /path/to/raw.json > Q1.1.md
"""
import argparse
import json


def strip_ext_prefix(name: str) -> str:
    """biorouter exposes tools as '<ext>__<toolname>' — keep the tool name only."""
    return name.split("__", 1)[1] if "__" in name else name


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--qname", required=True)
    ap.add_argument("--question", required=True)
    ap.add_argument("--elapsed", default="")
    ap.add_argument("--date", default="")
    ap.add_argument("--model", default="")
    ap.add_argument("--provider", default="")
    ap.add_argument("--kg", default="")  # "on" | "off"
    ap.add_argument("--json", required=True)
    a = ap.parse_args()

    try:
        d = json.load(open(a.json))
    except Exception as e:
        d = {"messages": [], "metadata": {"status": f"parse_error: {e}"}}
    msgs = d.get("messages", []) or []
    meta = d.get("metadata", {}) or {}

    steps = []          # (reasoning_text, [tool_names])
    tool_calls = []     # (name, arguments)
    final_text = ""
    for m in msgs:
        if m.get("role") != "assistant":
            continue
        texts, names = [], []
        for c in m.get("content", []) or []:
            t = c.get("type")
            if t == "text":
                if c.get("text"):
                    texts.append(c["text"])
            elif t in ("toolRequest", "toolReq"):
                val = (c.get("toolCall") or {}).get("value") or {}
                nm = strip_ext_prefix(val.get("name", "") or "")
                names.append(nm)
                tool_calls.append((nm, val.get("arguments", {})))
        text = "\n".join(texts).strip()
        steps.append((text, names))
        if text:
            final_text = text

    success = meta.get("status") == "completed"
    total_tokens = meta.get("total_tokens")

    o = []
    o += [f"# {a.qname}", ""]
    o += [f"**Question:** {a.question}", ""]
    if a.date:
        o += [f"**Date:** {a.date}"]
    model_line = f"{a.provider}/{a.model}" if a.provider and a.model else (a.model or a.provider)
    if model_line:
        o += [f"**Model:** {model_line}"]
    if a.kg:
        o += [f"**Knowledge graph:** {'enabled' if a.kg == 'on' else 'disabled (EHR-only)'}"]
    o += ["", "---", ""]

    o += ["## Agent's Response", "", final_text or "(no text response)", "", "---", ""]

    o += ["## Reasoning Steps", ""]
    for i, (text, names) in enumerate(steps, 1):
        o += [f"### Step {i}", ""]
        if text:
            o += [text, ""]
        if names:
            o += [f"**Tools Called:** {', '.join(names)}", ""]
        o += ["---", ""]

    o += ["## Performance Metrics", "", "| Metric | Value |", "|--------|-------|"]
    if a.elapsed:
        o += [f"| **Elapsed Time** | {a.elapsed} seconds |"]
    if total_tokens is not None:
        o += [f"| **Total Tokens** | {total_tokens} |"]
    o += [f"| **Tool Calls** | {len(tool_calls)} |"]
    o += [f"| **Success** | {success} |", ""]

    o += ["## Tools Used", ""]
    if tool_calls:
        for i, (nm, args) in enumerate(tool_calls, 1):
            o += [f"{i}. **{nm}**"]
            if args:
                o += [f"   - Input: `{json.dumps(args)}`"]
            o += [""]
    else:
        o += ["(no tools called)", ""]

    o += ["---", "", "*Generated by MedCP - Medical Model Context Protocol (via BioRouter)*"]
    print("\n".join(o))


if __name__ == "__main__":
    main()
